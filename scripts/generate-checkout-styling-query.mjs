// Generates app/utils/sync/checkoutStylingQuery.generated.ts: the query
// that reads a store's checkout and accounts branding, selecting every
// output field that has a same-named input field, so what's read can be
// written back with checkoutAndAccountsConfigurationUpdate. The branding
// tree is ~1,000 fields deep and changes each API version, so it's walked
// from the codegen schema rather than written by hand.
//
// Run after `pnpm graphql-codegen` (which writes the schema) whenever the
// Admin API version changes:
//   node scripts/generate-checkout-styling-query.mjs

import fs from "node:fs";

const API_VERSION = "2026-10";
const SCHEMA = `app/types/admin-${API_VERSION}.schema.json`;
const OUT = "app/utils/sync/checkoutStylingQuery.generated.ts";
const PREFIX = "CheckoutAndAccountsConfigurationBranding";

const schema = JSON.parse(fs.readFileSync(SCHEMA, "utf8"));
const types = new Map(
  (schema.data?.__schema ?? schema.__schema).types.map((t) => [t.name, t]),
);

const named = (ref) => (ref.ofType ? named(ref.ofType) : ref);

// Union outputs whose input is a different shape: read what's needed to
// rebuild the input (see checkoutBrandingInput.ts).
const UNIONS = {
  [`${PREFIX}ImageValue`]: `__typename ... on ${PREFIX}Image { image { url } }`,
  [`${PREFIX}FontGroup`]:
    `__typename ` +
    `... on ${PREFIX}CustomFontGroup { name loadingStrategy ` +
    `base { genericFileId sources weight } bold { genericFileId sources weight } } ` +
    `... on ${PREFIX}ShopifyFontGroup { name loadingStrategy ` +
    `base { sources weight } bold { sources weight } }`,
};

function selection(outputName, inputName) {
  const output = types.get(outputName);
  const input = types.get(inputName);
  const inputFields = new Map(
    (input?.inputFields ?? []).map((f) => [f.name, named(f.type)]),
  );
  const parts = [];
  for (const field of output.fields ?? []) {
    const inputType = inputFields.get(field.name);
    if (!inputType || field.isDeprecated) continue;
    const outputType = named(field.type);
    if (UNIONS[outputType.name]) {
      parts.push(`${field.name} { ${UNIONS[outputType.name]} }`);
    } else if (outputType.kind === "OBJECT") {
      const inner = selection(outputType.name, inputType.name);
      if (inner) parts.push(`${field.name} { ${inner} }`);
    } else if (outputType.kind === "SCALAR" || outputType.kind === "ENUM") {
      parts.push(field.name);
    } else {
      throw new Error(
        `Unhandled ${outputType.kind} at ${outputName}.${field.name}`,
      );
    }
  }
  return parts.join(" ");
}

// One configuration by ID: the branding tree alone costs ~50 points, so
// reading it across a list of configurations exceeds the 1,000-point
// single-query limit.
const query =
  `query CheckoutStyling($id: ID!) { ` +
  `checkoutAndAccountsConfiguration(id: $id) { ` +
  `branding { ${selection(PREFIX, `${PREFIX}Input`)} } } }`;

// Wrapped at word boundaries: the file stays under the 300-line limit and
// Prettier leaves template literals alone.
const lines = [];
let line = "";
for (const token of query.split(" ")) {
  if (line && line.length + token.length + 1 > 78) {
    lines.push(line);
    line = token;
  } else {
    line = line ? `${line} ${token}` : token;
  }
}
lines.push(line);

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-checkout-styling-query.mjs from the
// Admin API ${API_VERSION} schema. Don't edit by hand.

/** Scope read_checkout_and_accounts_configurations. One configuration's
 * branding: every field checkoutAndAccountsConfigurationUpdate also
 * accepts. */
export const CHECKOUT_STYLING_QUERY = \`#graphql
${lines.map((l) => `  ${l}`).join("\n")}
\`;
`,
);
console.log(`Wrote ${OUT} (${lines.length + 7} lines)`);
